#!/usr/bin/env python3
"""Make the report zones: where residents may send photo reports (Phase 4).

    python3 tools/report_zones.py           # after export_data.py and kml_to_geojson.py
    python3 tools/report_zones.py --check   # exit 1 if the saved files are out of date

INTERIM zones, until river corridors (docs/phase-4.md) replace them:
  * an area with prabhags (PMC) -> the outlines of its prabhags, from web/data/wards.geojson
  * an area without a ward map (Alandi) -> a box around its published spots, widened by PAD

Only Live areas with published spots get a zone. The same file is written twice: once for the
website (web/data/report-zones.geojson) and once next to the submit-report function, which
checks every report again on the server.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "web" / "data"
OUTPUTS = [WEB / "report-zones.geojson",
           ROOT / "supabase" / "functions" / "submit-report" / "report-zones.json"]
PAD_LAT = 0.008   # about 900 m north and south
PAD_LNG = 0.0085  # about 900 m east and west at Pune's latitude


def load(name):
    return json.loads((WEB / name).read_text(encoding="utf-8"))


def build():
    areas = load("areas.json")
    wards = load("wards.geojson")["features"]
    features = []
    for a in areas:
        if a["status"] != "Live" or not a.get("hotspot_count"):
            continue
        if a["prabhags"]:
            for w in wards:
                if w["properties"].get("area_id") == a["id"]:
                    features.append({
                        "type": "Feature",
                        "properties": {"area_id": a["id"], "kind": "prabhag",
                                       "label": f"{a['name']}: Prabhag {w['properties']['prabhag']}"},
                        "geometry": w["geometry"],
                    })
        else:
            (s, w_), (n, e) = a["bounds"]
            s, w_, n, e = round(s - PAD_LAT, 5), round(w_ - PAD_LNG, 5), round(n + PAD_LAT, 5), round(e + PAD_LNG, 5)
            features.append({
                "type": "Feature",
                "properties": {"area_id": a["id"], "kind": "interim-box",
                               "label": f"{a['name']}: about 900 m around the recorded spots"},
                "geometry": {"type": "Polygon",
                             "coordinates": [[[w_, s], [e, s], [e, n], [w_, n], [w_, s]]]},
            })
    missing = [a["id"] for a in areas
               if a["status"] == "Live" and a.get("hotspot_count")
               and not any(f["properties"]["area_id"] == a["id"] for f in features)]
    if missing:
        sys.exit(f"report zones: no zone for {', '.join(missing)} (run kml_to_geojson.py first?)")
    return {
        "type": "FeatureCollection",
        "note": ("Where residents may send photo reports. INTERIM: prabhag outlines for PMC areas, "
                 "a box around the recorded spots elsewhere; to be replaced by river corridors. "
                 "Generated by tools/report_zones.py; do not edit by hand."),
        "features": features,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only check the saved files are current")
    args = ap.parse_args()
    text = json.dumps(build(), ensure_ascii=False, separators=(",", ":")) + "\n"
    stale = [p for p in OUTPUTS if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            sys.exit("report zones out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale)
                     + " (run python3 tools/report_zones.py)")
        print("report zones: up to date")
        return
    for p in OUTPUTS:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    zones = json.loads(text)["features"]
    print(f"wrote {len(zones)} report zone(s) for "
          f"{len({z['properties']['area_id'] for z in zones})} area(s) to "
          + ", ".join(str(p.relative_to(ROOT)) for p in OUTPUTS))


if __name__ == "__main__":
    main()
